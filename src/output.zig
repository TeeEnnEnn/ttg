const std = @import("std");
const Utils = @import("utils.zig");

const MAP_SIZE = Utils.MAP_SIZE;
const Biome = Utils.Biome;
const biome_color = Utils.biome_color;
const Z_SCALE = Utils.Z_SCALE;

fn make_directory(io: std.Io, allocator: std.mem.Allocator, cwd: std.Io.Dir) ![:0]u8 {
    const name = "output";
    const cwd_path = try std.process.currentPathAlloc(io, allocator);
    const output_dir_path = try std.fs.path.joinZ(allocator, &.{ cwd_path, name });

    std.Io.Dir.createDir(cwd, io, name, .default_dir) catch |e| {
        switch (e) {
            error.PathAlreadyExists => {},
            else => return e,
        }
    };
    return output_dir_path;
}

pub fn to_ppm_6(io: std.Io, allocator: std.mem.Allocator, map: []Biome) !void {
    const cwd = std.Io.Dir.cwd();
    const output_dir_path = try make_directory(io, allocator, cwd);

    const output_file_path = try std.fs.path.joinZ(allocator, &.{ output_dir_path, "render_p6.ppm" });
    _ = try cwd.createFile(io, output_file_path, .{});
    const out_file = try cwd.openFile(io, output_file_path, .{ .mode = .read_write });

    const file_header = try std.mem.Allocator.print(allocator, "P6\n{d} {d}\n{d}\n", .{ MAP_SIZE, MAP_SIZE, 255 });

    // buffer for the file writer, it flushes automatically when full
    var write_buffer: [64 * 1024]u8 = undefined;
    var file_writer = out_file.writer(io, &write_buffer);
    const w = &file_writer.interface;

    try w.writeAll(file_header);

    for (0..MAP_SIZE * MAP_SIZE) |i| {
        const y: usize = i / MAP_SIZE;
        const x: usize = i % MAP_SIZE;

        const color = biome_color(map[y * MAP_SIZE + x]);
        try w.writeByte(color.r);
        try w.writeByte(color.g);
        try w.writeByte(color.b);
    }

    try w.flush();
    out_file.close(io);
}

pub fn to_ply(io: std.Io, allocator: std.mem.Allocator, biome_map: []Biome, height_map: []f64) !void {
    const cwd = std.Io.Dir.cwd();
    const output_dir_path = try make_directory(io, allocator, cwd);

    const output_file_path = try std.fs.path.joinZ(allocator, &.{ output_dir_path, "render_ply.ply" });
    _ = try cwd.createFile(io, output_file_path, .{});
    const out_file = try cwd.openFile(io, output_file_path, .{ .mode = .read_write });

    // buffer for the file writer, it flushes automatically when full
    var write_buffer: [64 * 1024]u8 = undefined;
    var file_writer = out_file.writer(io, &write_buffer);
    const w = &file_writer.interface;

    try w.print(
        \\ply
        \\format binary_little_endian 1.0
        \\comment terrain mesh generated by ttg
        \\element vertex {d}
        \\property float x
        \\property float y
        \\property float z
        \\property uchar red
        \\property uchar green
        \\property uchar blue
        \\element face {d}
        \\property list uchar int vertex_indices
        \\end_header
        \\
    , .{ MAP_SIZE * MAP_SIZE, ((MAP_SIZE - 1) * (MAP_SIZE - 1)) * 2 });

    // drawing vertices and colors
    for (0..MAP_SIZE * MAP_SIZE) |i| {
        const y: usize = i / MAP_SIZE;
        const x: usize = i % MAP_SIZE;

        const height = height_map[y * @as(usize, @intCast(MAP_SIZE)) + x];

        try w.writeAll(&std.mem.toBytes(@as(f32, @floatFromInt(x))));
        try w.writeAll(&std.mem.toBytes(@as(f32, @floatCast(height * Z_SCALE))));
        try w.writeAll(&std.mem.toBytes(@as(f32, @floatFromInt(y))));

        const color = biome_color(biome_map[y * MAP_SIZE + x]);
        try w.writeByte(color.r);
        try w.writeByte(color.g);
        try w.writeByte(color.b);
    }

    const W = MAP_SIZE;
    // drawing faces
    // faces are indexes into the vertex list
    // faces must be drawn in triangles
    for (0..MAP_SIZE - 1) |y| {
        for (0..MAP_SIZE - 1) |x| {
            const b: i32 = @intCast(y * MAP_SIZE + x);

            // normals must face upwards so this must be counter clockwise
            const A = b; // (x, y)
            const C = b + 1; // (x + 1, y)
            const D = b + W; // (x, y+1)
            const E = b + W + 1; // (x+1, y+1)

            // triangle 1: A, C, E -> (b, b+1, b+W+1)
            // triangle 2: A, E, D -> (b, b+W+1, b+W)

            try w.writeByte(3); // number of vertices in a triangle - the count
            try w.writeAll(&std.mem.toBytes(A));
            try w.writeAll(&std.mem.toBytes(C));
            try w.writeAll(&std.mem.toBytes(E));
            try w.writeByte(3); // number of vertices in a triangle - the count
            try w.writeAll(&std.mem.toBytes(A));
            try w.writeAll(&std.mem.toBytes(E));
            try w.writeAll(&std.mem.toBytes(D));
        }
    }
    try w.flush();
    out_file.close(io);
}
